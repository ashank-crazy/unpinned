// Writes dist/sw.js after `vite build`. The service worker keeps the app
// working offline and receives photos shared from other apps on Android.
// It never sends anything anywhere: it only answers requests for this site's
// own files.

import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = fileURLToPath(new URL('../dist/', import.meta.url));
const tesseract = JSON.parse(await readFile(new URL('../node_modules/tesseract.js/package.json', import.meta.url), 'utf8'));

async function walk(dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(path)));
    else files.push(relative(dist, path).split(sep).join('/'));
  }
  return files;
}

// The text reader's engine and language data (about 8 MB) are cached the first
// time they are used instead of up front, so a first visit stays light.
const shell = (await walk(dist))
  .filter((file) => !file.endsWith('.map') && !file.startsWith('vendor/') && file !== 'sw.js' && file !== 'index.html')
  .sort();

// A new version whenever any file, or this script's caching rules, change.
const hash = createHash('sha256').update(await readFile(fileURLToPath(import.meta.url)));
for (const file of ['index.html', ...shell]) hash.update(file).update(await readFile(join(dist, file)));
const version = hash.digest('hex').slice(0, 12);

const worker = `// Generated by scripts/build-sw.mjs. Do not edit.
const SHELL_CACHE = 'unpinned-shell-${version}';
const VENDOR_CACHE = 'unpinned-vendor-tesseract-${tesseract.version}';
const SHARE_CACHE = 'unpinned-share';
const SCOPE = self.registration.scope;
const SHELL = ${JSON.stringify(['./', ...shell], null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL_CACHE).then((cache) => cache.addAll(SHELL)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        const stale = (key.startsWith('unpinned-shell-') && key !== SHELL_CACHE) || (key.startsWith('unpinned-vendor-') && key !== VENDOR_CACHE);
        if (stale) await caches.delete(key);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.method === 'POST' && url.href === new URL('./share-target', SCOPE).href) {
    event.respondWith(receiveShare(request));
    return;
  }
  if (request.method !== 'GET') return;
  if (request.mode === 'navigate') {
    event.respondWith(fromCache(SHELL_CACHE, new URL('./', SCOPE).href, request));
  } else if (url.pathname.includes('/vendor/')) {
    event.respondWith(fromCache(VENDOR_CACHE, request, request, true));
  } else {
    event.respondWith(fromCache(SHELL_CACHE, request, request));
  }
});

async function fromCache(cacheName, key, request, store = false) {
  const cache = await caches.open(cacheName);
  // Scripts load with an Origin header and servers may answer "Vary: Origin",
  // which would make every cached copy miss. These files never vary.
  const cached = await cache.match(key, { ignoreVary: true });
  if (cached) return cached;
  const response = await fetch(request);
  if (store && response.ok) await cache.put(request, response.clone());
  return response;
}

// Android's share sheet sends the photo here. Keep it on this device just long
// enough for the page to pick it up, then the page deletes it.
async function receiveShare(request) {
  try {
    const form = await request.formData();
    const file = form.getAll('photo').find((item) => item instanceof File);
    if (file) {
      const cache = await caches.open(SHARE_CACHE);
      await cache.put(
        new URL('./shared-photo', SCOPE).href,
        new Response(file, { headers: { 'Content-Type': file.type || 'application/octet-stream', 'X-File-Name': encodeURIComponent(file.name || 'shared-photo') } }),
      );
    }
  } catch {
    // The page shows a message when no photo arrives.
  }
  return Response.redirect(new URL('./?shared=1', SCOPE).href, 303);
}
`;

await writeFile(join(dist, 'sw.js'), worker);
console.log(`Wrote dist/sw.js (${shell.length + 1} files to keep offline, version ${version}).`);
